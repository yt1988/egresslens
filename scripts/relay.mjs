#!/usr/bin/env node
// Writes src/relay.mjs: the IPv4 /24s and IPv6 /32s in Apple's iCloud Private Relay exit list
// (https://mask-api.icloud.com/egress-ip-ranges.csv). The list itself is about 12 MB and sends no CORS header, so a
// page cannot read it; this digest is what the page checks an exit's addresses against. Apple updates the list
// hourly, so the digest is refreshed by hand now and then (`npm run relay`) and committed.
// Usage: node scripts/relay.mjs        (needs network; keeps the current file if the fetch fails)
import { writeFile } from "node:fs/promises";

const URL_ = "https://mask-api.icloud.com/egress-ip-ranges.csv";
const out = new URL("../src/relay.mjs", import.meta.url);

const r = await fetch(URL_, { signal: AbortSignal.timeout(60_000) });
if (!r.ok) throw new Error(`Apple's list answered HTTP ${r.status}`);
const text = await r.text();

const v4 = new Map(), v6 = new Set();               // "a.b" → Set of third octets; v6 → "x:y" of the /32
const net = cidr => {
  const [addr, bits] = cidr.split("/");
  const n = Number(bits);
  if (addr.includes(":")) {
    if (n < 32) return null;                          // a /32 is the coarsest IPv6 key we keep
    const [a, b] = addr.toLowerCase().split(":");
    return { v6: `${parseInt(a, 16).toString(16)}:${parseInt(b, 16).toString(16)}` };
  }
  if (n <= 16) return null;
  const o = addr.split(".").map(Number);
  if (o.length !== 4 || o.some(x => !(x >= 0 && x <= 255))) return null;
  return { v4: [`${o[0]}.${o[1]}`, o[2]] };
};
let rows = 0;
for (const line of text.split("\n")) {
  const cidr = (line.split(",")[0] || "").trim();
  if (!/^[0-9a-f:.]+(\/\d+)?$/i.test(cidr)) continue;
  const k = net(cidr);
  if (!k) continue;
  rows++;
  if (k.v6) v6.add(k.v6);
  else { const set = v4.get(k.v4[0]) || v4.set(k.v4[0], new Set()).get(k.v4[0]); set.add(k.v4[1]); }
}
if (!v4.size || !v6.size) throw new Error("the list had no usable ranges");

const wrap = (list, width = 104) => {
  const out = []; let line = "";
  for (const x of list) {
    if (line && line.length + x.length + 1 > width) { out.push(line); line = ""; }
    line += (line ? " " : "") + x;
  }
  if (line) out.push(line);
  return out.map(s => "    " + JSON.stringify(s)).join(" +\n");
};
const keys = [...v4.keys()].sort((a, b) => Number(a.split(".")[0]) - Number(b.split(".")[0]) || Number(a.split(".")[1]) - Number(b.split(".")[1]));
const file = `// iCloud Private Relay's egress ranges, generated by scripts/relay.mjs from Apple's list
// (https://mask-api.icloud.com/egress-ip-ranges.csv, ${new Date().toISOString().slice(0, 10)}): ${rows} ranges, kept as
// the IPv4 /24s and IPv6 /32s that contain them. The page cannot read Apple's 12 MB list itself (no CORS header).
// Refresh: npm run relay, then commit this file.
export const RELAY4 = {
${keys.map(k => `  ${JSON.stringify(k)}: ${wrap([...v4.get(k)].sort((a, b) => a - b).map(String))},`).join("\n")}
};
export const RELAY6 = ${wrap([...v6].sort())};

const N4 = new Map([...Object.entries(RELAY4)].map(([k, v]) => [k, new Set(v.split(" "))]));
const N6 = new Set(RELAY6.split(" "));
// an address inside Apple's published relay ranges: the exit a Private Relay connection leaves from
export const isRelayIp = ip => {
  const s = String(ip || "").toLowerCase();
  if (s.includes(":")) { const [a, b] = s.split(":"); return N6.has(parseInt(a, 16).toString(16) + ":" + parseInt(b, 16).toString(16)); }
  const o = s.split(".").map(Number);
  return o.length === 4 && !!N4.get(o[0] + "." + o[1])?.has(String(o[2]));
};
`;
await writeFile(out, file);
console.log(`wrote src/relay.mjs: ${v4.size} IPv4 /16s, ${[...v4.values()].reduce((a, s) => a + s.size, 0)} /24s, ${v6.size} IPv6 /32s`);
